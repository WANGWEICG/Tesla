import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const files={
  '/':['text/html',read('../public/index.html')],
  '/app.js':['text/javascript',read('../public/app.js')],
  '/style.css':['text/css',read('../public/style.css')],
  '/model.mjs':['text/javascript',read('../model.mjs')],
  '/manifest.webmanifest':['application/manifest+json',read('../public/manifest.webmanifest')],
  '/icon.svg':['image/svg+xml',read('../public/icon.svg')],
  '/setup':['text/html',read('./setup.html')],
  '/setup.js':['text/javascript',read('./setup.js')]
};
files['/index.html']=files['/'];
writeFileSync(fileURLToPath(new URL('./generated-assets.mjs',import.meta.url)),'// Generated by node build.mjs. No secrets or server data.\nexport const ASSETS='+JSON.stringify(files)+';\n');
console.log('Built embedded frontend assets for Cloudflare Workers.');
